// Main-session tool (planning, not imported): merges module inboxes into shared files.
// Usage (from the course root): node curriculum/tools/merge-inboxes.mjs
// Idempotent: rebuilds glossary, external resources, laws index, templates README and the
// question-bank master from all inbox files. Numbers are merged by hand.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";

const require = createRequire("C:/Users/TalGiladi/OneDrive/repos/tals-academy/package.json");
const yaml = require("js-yaml");
const read = (f) => fs.readFileSync(f, "utf8").replace(/\r/g, "");
const list = (dir, re) => (fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => re.test(f)).sort() : []);

// Templates: move drafts that are not yet published.
const tIn = "curriculum/inbox/templates";
for (const f of list(tIn, /\.md$/)) {
  if (!fs.existsSync(path.join("templates", f))) fs.renameSync(path.join(tIn, f), path.join("templates", f));
  else console.log(`template exists, left in inbox: ${f}`);
}
const tItems = list("templates", /\.md$/)
  .filter((f) => f !== "README.md")
  .map((f) => {
    const h1 = (read(path.join("templates", f)).match(/^# (.+)$/m) ?? [, f])[1].trim();
    return `- [${h1}](${f})`;
  });
const tHead = read("templates/README.md").split("\n## All templates")[0].trimEnd();
fs.writeFileSync("templates/README.md", `${tHead}\n\n## All templates\n\n${tItems.join("\n")}\n`);

// Glossary: dedupe by term, sort by Hebrew term.
const terms = new Map();
for (const f of list("curriculum/glossary-inbox", /^module-\d{2}\.md$/))
  for (const line of read(`curriculum/glossary-inbox/${f}`).split("\n")) {
    const m = /^- \*\*(.+?)\*\*/.exec(line);
    if (m && !terms.has(m[1])) terms.set(m[1], line.trim());
  }
const gHead = read("glossary.md").split("\n## Terms")[0].trimEnd();
const gLines = [...terms.keys()].sort((a, b) => a.localeCompare(b, "he")).map((k) => terms.get(k));
fs.writeFileSync("glossary.md", `${gHead}\n\n## Terms\n\n${gLines.join("\n")}\n`);

// External resources: merge table rows, dedupe by URL column.
const rows = new Map();
let header = "";
for (const f of list("curriculum/inbox", /^module-\d{2}-external\.md$/)) {
  const lines = read(`curriculum/inbox/${f}`).split("\n").filter((l) => l.startsWith("|"));
  if (!header && lines.length >= 2) header = `${lines[0]}\n${lines[1]}`;
  for (const l of lines.slice(2)) {
    const url = (l.match(/https?:\/\/[^\s|)]+/) ?? [l])[0];
    if (!rows.has(url)) rows.set(url, l);
  }
}
const eHead = read("references/external-resources.md").split("\n## Catalog")[0].trimEnd();
fs.writeFileSync("references/external-resources.md", `${eHead}\n\n## Catalog\n\n${header}\n${[...rows.values()].join("\n")}\n`);

// Laws and rulings: collect bullet lines under each "## " heading, dedupe by line text.
const sections = new Map();
for (const f of list("curriculum/inbox", /^module-\d{2}-laws\.md$/)) {
  let sec = "Laws";
  for (const line of read(`curriculum/inbox/${f}`).split("\n")) {
    const h = /^## (.+)$/.exec(line);
    if (h) { sec = h[1].trim(); continue; }
    if (!line.startsWith("- ")) continue;
    if (!sections.has(sec)) sections.set(sec, new Set());
    sections.get(sec).add(line.trim());
  }
}
const lHead = read("references/laws-index.md").split("\n## ")[0].trimEnd();
const lBody = [...sections].map(([s, set]) => `## ${s}\n\n${[...set].join("\n")}`).join("\n\n");
fs.writeFileSync("references/laws-index.md", `${lHead}\n\n${lBody}\n`);

// Question bank master.
const all = [];
for (const f of list("curriculum/question-bank", /^module-\d{2}\.yaml$/))
  all.push(...(yaml.load(read(`curriculum/question-bank/${f}`)) ?? []));
fs.writeFileSync(
  "curriculum/question-bank/master.yaml",
  `# Generated by curriculum/tools/merge-inboxes.mjs — do not edit; edit module-NN.yaml instead.\n` +
    yaml.dump(all, { lineWidth: 100, noRefs: true }),
);
console.log(`templates ${tItems.length}, terms ${terms.size}, external ${rows.size}, law sections ${sections.size}, bank ${all.length}`);
